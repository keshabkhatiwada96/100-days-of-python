# Docstrings in Python
def greet():
    """This function prints a greeting message."""
    print("Hello!")

greet()
print(greet.__doc__)

# Comment vs Docstring
# Comment:
# Starts with #
# Ignored by Python
# Used for writing notes for programmers

# Docstring:
# Uses """ """ or ''' '''
# Stored by Python
# Used to describe functions, classes, and modules

