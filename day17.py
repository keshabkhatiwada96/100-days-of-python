# break and continue statement


# break statement
for r in range (1 , 20):
   
    if r == 17:
        break    #since i have used (break) when the value of r is 17 the code stops.
    print(r)

print("+++++++++++++++++++++++++++++++++")

# continue statement

for r in range(1, 20):

    if r == 17:
        continue    #since i have used (continue) when the value of r is 17 the code skips r and continue.
    print(r)

print("+++++++++++++++++++++++++++++++++")